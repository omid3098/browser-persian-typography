const fs = require("node:fs")
const path = require("node:path")
const assert = require("node:assert/strict")
const { dist, files } = require("../scripts/build.cjs")
const shipped = fs.readdirSync(dist, { recursive: true }).filter(file => fs.statSync(path.join(dist, file)).isFile()).sort()
assert.deepEqual(shipped.map(file => file.replaceAll("\\", "/")), [...files].sort(), "dist must contain exactly the shipped files; run npm run build")
const bytes = shipped.reduce((sum, file) => sum + fs.statSync(path.join(dist, file)).size, 0)
console.log(`Package: ${bytes} bytes / 300000 bytes (uncompressed; includes font licence)`)
assert(bytes <= 300000, "Extension exceeds its size budget")
console.log(`Measured distribution: ${dist}`)
module.exports = { files, bytes }
